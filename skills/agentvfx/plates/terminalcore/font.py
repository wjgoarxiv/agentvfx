def glyph(ch):
    """Return a 7x5 tuple-of-tuples (1 = lit) for ch; unknown characters render as blank."""
    rows = _G.get(ch.upper(), _G[" "]).split("|")
    return tuple(tuple(1 if c == "#" else 0 for c in r) for r in rows)
